/**
 * SUPCheckout admin design tokens: load, resolve and render.
 *
 * The source of truth is `assets/admin/src/tokens/*.tokens.json`, written in a
 * DTCG-style `{ "$value", "$type" }` shape. Token paths flatten to names
 * without the `--sup-` prefix (`color.bg.canvas` -> `color-bg-canvas`); an
 * alias `{color.bg.canvas}` renders as `var(--sup-color-bg-canvas)`.
 *
 * Three tiers: primitives (`palette-*`, never used by components), semantic
 * tokens in light and dark sets, and component tokens that reference semantic
 * tokens only. The accent ramp (`palette-accent-*`) comes from the WordPress
 * admin color scheme, unless `brand.tokens.json` sets one.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { formatHex, parse } from 'culori';

export const ROOT = join(
	dirname( fileURLToPath( import.meta.url ) ),
	'..',
	'..',
	'..'
);
export const TOKENS_DIR = join( ROOT, 'assets', 'admin', 'src', 'tokens' );
export const DEFAULT_BRAND_PATH = join( TOKENS_DIR, 'brand.tokens.json' );

/** The nine core WordPress admin color schemes; `fresh` first as the default. */
export const SCHEME_NAMES = Object.freeze( [
	'fresh',
	'light',
	'modern',
	'blue',
	'coffee',
	'ectoplasm',
	'midnight',
	'ocean',
	'sunrise',
] );

/** The scheme used on the root and for any unknown or custom scheme. */
export const DEFAULT_SCHEME = 'fresh';

/** Steps of every accent ramp, light and dark. */
export const ACCENT_STEPS = Object.freeze( [
	'50',
	'100',
	'200',
	'300',
	'400',
	'500',
	'600',
	'700',
	'800',
	'900',
] );

const SCOPE = '.supcheckout-admin';
const DARK_SYSTEM_MEDIA = '@media (prefers-color-scheme: dark)';
const LIGHT_EXCLUDED = ':not([data-sup-theme="light"])';
const DARK_EXPLICIT = '[data-sup-theme="dark"]';
const ARABIC_LANGS = [ 'ar', 'fa', 'ur' ];
const REDUCED_MOTION_MEDIA = '@media (prefers-reduced-motion: reduce)';
const BRAND_FONT_KEYS = [ 'sans', 'arabic', 'mono' ];
const RADIUS_SCALE_MAX = 2;
const UNSCALED_RADII = new Set( [ 'radius-pill' ] );
const ALIAS = /\{([a-z0-9-]+(?:\.[a-z0-9-]+)*)\}/g;
const VAR_ONLY = /^var\(--sup-([a-z0-9-]+)\)$/;
const HEX6 = /^#[0-9a-fA-F]{6}$/;

const HEADER = [
	'/*',
	' * SUPCheckout admin design tokens (--sup-*).',
	' *',
	' * Generated by tools/admin-ui/tokens/build-tokens.mjs from',
	' * assets/admin/src/tokens/*.tokens.json. Do not edit by hand.',
	' */',
].join( '\n' );
// The admin-color-* body classes are WordPress core's, and the scheme rules
// set only palette-accent-* tokens, which no later (lower-specificity) rule
// sets, so their order is safe.
const SCHEME_LINT_NOTE =
	'/* stylelint-disable selector-class-pattern, no-descending-specificity -- WordPress core owns the admin-color-* body classes; scheme rules set only palette-accent-* tokens. */';

function readJsonFile( path ) {
	return JSON.parse( readFileSync( path, 'utf8' ) );
}

function isPlainObject( value ) {
	return (
		typeof value === 'object' && value !== null && ! Array.isArray( value )
	);
}

function isMetaKey( key ) {
	return key.startsWith( '$' );
}

/**
 * Converts a DTCG `$value` into a CSS value, rendering aliases as `var()`.
 *
 * @param {string|number} value Raw `$value`.
 * @return {string} CSS value.
 */
function toCssValue( value ) {
	return String( value ).replace(
		ALIAS,
		( match, path ) => `var(--sup-${ path.split( '.' ).join( '-' ) })`
	);
}

/**
 * Flattens a token tree into `{ 'a-b-c': cssValue }`.
 *
 * @param {Object} node   Token tree node.
 * @param {string} prefix Name prefix of the node.
 * @return {Record<string,string>} Flat tokens.
 */
function flatten( node, prefix = '' ) {
	const out = {};
	for ( const [ key, child ] of Object.entries( node ?? {} ) ) {
		if ( isMetaKey( key ) ) {
			continue;
		}
		const name = prefix ? `${ prefix }-${ key }` : key;
		if ( isPlainObject( child ) && '$value' in child ) {
			out[ name ] = toCssValue( child.$value );
		} else if ( isPlainObject( child ) ) {
			Object.assign( out, flatten( child, name ) );
		} else {
			throw new Error( `token ${ name } must be an object with $value` );
		}
	}
	return out;
}

/**
 * Accent ramp `{ '600': { $value } }` as `{ 'palette-accent-600': '#rrggbb' }`.
 *
 * @param {Object} ramp Ramp node.
 * @return {Record<string,string>} Primitive accent tokens.
 */
function accentRamp( ramp ) {
	return Object.fromEntries(
		ACCENT_STEPS.map( ( step ) => [
			`palette-accent-${ step }`,
			String( ramp[ step ].$value ).toLowerCase(),
		] )
	);
}

function validateBrandLeaf( node, path, errors, check ) {
	if ( ! isPlainObject( node ) || ! ( '$value' in node ) ) {
		errors.push( `brand ${ path } must be an object with $value` );
		return;
	}
	const unknown = Object.keys( node ).filter( ( key ) => ! isMetaKey( key ) );
	for ( const key of unknown ) {
		errors.push( `unknown brand key: ${ path }.${ key }` );
	}
	const message = check( node.$value );
	if ( message ) {
		errors.push( `brand ${ path } ${ message }` );
	}
}

function validateBrandBranch( node, path, allowed, errors, visit ) {
	if ( ! isPlainObject( node ) ) {
		errors.push( `brand ${ path } must be an object` );
		return;
	}
	for ( const [ key, child ] of Object.entries( node ) ) {
		if ( isMetaKey( key ) ) {
			continue;
		}
		if ( ! allowed.includes( key ) ) {
			errors.push( `unknown brand key: ${ path }.${ key }` );
			continue;
		}
		visit( key, child, `${ path }.${ key }` );
	}
}

function validateAccentRamp( ramp, path, errors ) {
	validateBrandBranch(
		ramp,
		path,
		ACCENT_STEPS,
		errors,
		( step, leaf, leafPath ) =>
			validateBrandLeaf( leaf, leafPath, errors, ( value ) =>
				typeof value === 'string' && HEX6.test( value )
					? ''
					: 'must be a #rrggbb color'
			)
	);
	if ( ! isPlainObject( ramp ) ) {
		return;
	}
	const missing = ACCENT_STEPS.filter( ( step ) => ! ( step in ramp ) );
	if ( missing.length > 0 ) {
		errors.push(
			`brand accent ramp ${ path } is missing steps ${ missing.join( ', ' ) }`
		);
	}
}

function validateFontStack( value ) {
	const valid =
		typeof value === 'string' &&
		value.trim() !== '' &&
		value.length <= 300 &&
		! /[;{}]|url\(/i.test( value );
	return valid ? '' : 'must be a font stack without ; { } or url(';
}

function validateRadiusScale( value ) {
	const valid =
		typeof value === 'number' &&
		Number.isFinite( value ) &&
		value >= 0 &&
		value <= RADIUS_SCALE_MAX;
	return valid ? '' : `must be a number from 0 to ${ RADIUS_SCALE_MAX }`;
}

/**
 * Validates a brand file against the allowlist.
 *
 * Allowed: `palette.accent.light.*` and `palette.accent.dark.*` (complete
 * `#rrggbb` ramps, both or neither), `font.family.sans|arabic|mono` and
 * `radius.scale`. Keys starting with `$` are metadata.
 *
 * @param {unknown} json Parsed brand file.
 * @return {string[]} Error messages; empty when valid.
 */
export function validateBrand( json ) {
	if ( ! isPlainObject( json ) ) {
		return [ 'brand file must be a JSON object' ];
	}
	const errors = [];
	const sections = {
		palette: ( node, path ) =>
			validateBrandBranch(
				node,
				path,
				[ 'accent' ],
				errors,
				( key, accent, accentPath ) => {
					validateBrandBranch(
						accent,
						accentPath,
						[ 'light', 'dark' ],
						errors,
						( mode, ramp, rampPath ) =>
							validateAccentRamp( ramp, rampPath, errors )
					);
					if ( isPlainObject( accent ) ) {
						for ( const mode of [ 'light', 'dark' ] ) {
							if ( ! ( mode in accent ) ) {
								errors.push(
									`brand accent ramp ${ accentPath }.${ mode } is missing`
								);
							}
						}
					}
				}
			),
		font: ( node, path ) =>
			validateBrandBranch(
				node,
				path,
				[ 'family' ],
				errors,
				( key, family, familyPath ) =>
					validateBrandBranch(
						family,
						familyPath,
						BRAND_FONT_KEYS,
						errors,
						( name, leaf, leafPath ) =>
							validateBrandLeaf(
								leaf,
								leafPath,
								errors,
								validateFontStack
							)
					)
			),
		radius: ( node, path ) =>
			validateBrandBranch(
				node,
				path,
				[ 'scale' ],
				errors,
				( key, leaf, leafPath ) =>
					validateBrandLeaf(
						leaf,
						leafPath,
						errors,
						validateRadiusScale
					)
			),
	};
	for ( const [ key, node ] of Object.entries( json ) ) {
		if ( isMetaKey( key ) ) {
			continue;
		}
		if ( ! Object.hasOwn( sections, key ) ) {
			errors.push( `unknown brand key: ${ key }` );
			continue;
		}
		sections[ key ]( node, key );
	}
	return errors;
}

function scaleRadius( value, scale ) {
	const px = /^(\d+(?:\.\d+)?)px$/.exec( value );
	if ( ! px ) {
		throw new Error( `radius token value ${ value } is not a px length` );
	}
	const scaled = Math.round( Number( px[ 1 ] ) * scale );
	return scaled === 0 ? '0' : `${ scaled }px`;
}

function applyBrandBase( base, brand ) {
	const out = { ...base };
	for ( const name of BRAND_FONT_KEYS ) {
		const leaf = brand.font?.family?.[ name ];
		if ( leaf ) {
			out[ `font-family-${ name }` ] = leaf.$value.trim();
		}
	}
	const scale = brand.radius?.scale?.$value;
	if ( scale !== undefined ) {
		for ( const key of Object.keys( out ) ) {
			if ( key.startsWith( 'radius-' ) && ! UNSCALED_RADII.has( key ) ) {
				out[ key ] = scaleRadius( out[ key ], scale );
			}
		}
	}
	return out;
}

/**
 * @typedef {'fresh'|'light'|'modern'|'blue'|'coffee'|'ectoplasm'|'midnight'|'ocean'|'sunrise'} SchemeName
 * @typedef {{ light: Record<string,string>, dark: Record<string,string> }} ModeSet
 * @typedef {Object} TokenSet
 * @property {Record<string,string>}                                             primitives  Mode-independent `palette-*` tokens.
 * @property {ModeSet}                                                           semantic    Full semantic sets per mode.
 * @property {Record<string,string>}                                             component   Component tokens (semantic aliases).
 * @property {Record<SchemeName,ModeSet>}                                        schemes     `palette-accent-*` ramps per scheme and mode.
 * @property {boolean}                                                           brandAccent True when the brand file replaces the scheme accents.
 * @property {{ arabic: Record<string,string>, compact: Record<string,string> }} modifiers   Scoped overrides.
 */

/**
 * Loads and merges the token JSON files.
 *
 * @param {{ brandPath?: string }} [opts] Brand file to merge (default: the shipped `brand.tokens.json`).
 * @return {TokenSet} Resolved token set.
 */
export function loadTokens( opts = {} ) {
	const core = readJsonFile( join( TOKENS_DIR, 'core.tokens.json' ) );
	const adminSchemes = readJsonFile(
		join( TOKENS_DIR, 'admin-schemes.tokens.json' )
	);
	const brand = readJsonFile( opts.brandPath ?? DEFAULT_BRAND_PATH );
	const errors = validateBrand( brand );
	if ( errors.length > 0 ) {
		throw new Error( errors.join( '\n' ) );
	}

	const base = applyBrandBase( flatten( core.semantic.base ), brand );
	const brandAccent = Boolean( brand.palette?.accent );
	const brandRamps = brandAccent
		? {
				light: accentRamp( brand.palette.accent.light ),
				dark: accentRamp( brand.palette.accent.dark ),
			}
		: null;
	const schemes = Object.fromEntries(
		SCHEME_NAMES.map( ( name ) => {
			const entry = adminSchemes.schemes[ name ];
			if ( ! entry ) {
				throw new Error(
					`admin-schemes.tokens.json is missing scheme ${ name }`
				);
			}
			const ramps = brandRamps ?? {
				light: accentRamp( entry.light ),
				dark: accentRamp( entry.dark ),
			};
			return [
				name,
				{ light: { ...ramps.light }, dark: { ...ramps.dark } },
			];
		} )
	);

	return {
		primitives: flatten( core.palette, 'palette' ),
		semantic: {
			light: { ...base, ...flatten( core.semantic.light ) },
			dark: { ...base, ...flatten( core.semantic.dark ) },
		},
		component: flatten( core.component ),
		schemes,
		brandAccent,
		modifiers: {
			arabic: flatten( core.modifiers.arabic ),
			compact: flatten( core.modifiers.compact ),
		},
	};
}

function lookupTable( set, mode, scheme ) {
	return {
		...set.primitives,
		...set.schemes[ scheme ][ mode ],
		...set.semantic[ mode ],
		...set.component,
	};
}

/**
 * Resolves a color token to `#rrggbb` for a mode and admin scheme.
 *
 * @param {TokenSet}       set      Token set.
 * @param {'light'|'dark'} mode     Color mode.
 * @param {string}         token    Token name without `--sup-`.
 * @param {SchemeName}     [scheme] Admin color scheme (default `fresh`).
 * @return {string} Opaque color as `#rrggbb`.
 */
export function resolveColor( set, mode, token, scheme = DEFAULT_SCHEME ) {
	const table = lookupTable( set, mode, scheme );
	const seen = new Set();
	let name = token;
	for (;;) {
		if ( ! Object.hasOwn( table, name ) ) {
			throw new Error( `unknown token: ${ name }` );
		}
		if ( seen.has( name ) ) {
			throw new Error( `circular token reference: ${ token }` );
		}
		seen.add( name );
		const value = table[ name ];
		const alias = VAR_ONLY.exec( value );
		if ( alias ) {
			name = alias[ 1 ];
			continue;
		}
		const color = parse( value );
		if ( ! color ) {
			throw new Error( `token ${ token } is not a color: ${ value }` );
		}
		if ( color.alpha !== undefined && color.alpha < 1 ) {
			throw new Error( `token ${ token } is translucent: ${ value }` );
		}
		return formatHex( color );
	}
}

function naturalCompare( a, b ) {
	const pa = a.match( /\d+|\D+/g );
	const pb = b.match( /\d+|\D+/g );
	for ( let i = 0; i < Math.min( pa.length, pb.length ); i++ ) {
		const x = pa[ i ];
		const y = pb[ i ];
		if ( x === y ) {
			continue;
		}
		const nx = /^\d/.test( x );
		const ny = /^\d/.test( y );
		if ( nx && ny ) {
			return Number( x ) - Number( y ) || ( x < y ? -1 : 1 );
		}
		return x < y ? -1 : 1;
	}
	return pa.length - pb.length;
}

function shortHex( value ) {
	return value.replace(
		/#([0-9a-f])\1([0-9a-f])\2([0-9a-f])\3\b/g,
		( match, r, g, b ) => `#${ r }${ g }${ b }`
	);
}

function rule( selectors, tokens, extra = [], indent = '' ) {
	const lines = Object.keys( tokens )
		.sort( naturalCompare )
		.map(
			( name ) =>
				`${ indent }\t--sup-${ name }: ${ shortHex( tokens[ name ] ) };`
		);
	for ( const [ prop, value ] of extra ) {
		lines.push( `${ indent }\t${ prop }: ${ value };` );
	}
	const prelude = selectors
		.map( ( selector ) => `${ indent }${ selector }` )
		.join( ',\n' );
	return `${ prelude } {\n${ lines.join( '\n' ) }\n${ indent }}`;
}

function atRule( prelude, inner ) {
	return `${ prelude } {\n\n${ inner }\n}`;
}

function changedFrom( base, next ) {
	return Object.fromEntries(
		Object.entries( next ).filter(
			( [ key, value ] ) => base[ key ] !== value
		)
	);
}

/**
 * Adds every token whose value references a changed token (transitively).
 *
 * Needed where the overriding selector can match a descendant of the root
 * (density): a custom property's `var()` is resolved where it is declared, so
 * a dependant declared on the root would keep the root's value.
 *
 * @param {Record<string,string>} changed    Overridden tokens.
 * @param {Record<string,string>} candidates Tokens that may depend on them.
 * @return {Record<string,string>} The overrides plus re-declared dependants.
 */
function withDependants( changed, candidates ) {
	const out = { ...changed };
	let grew = true;
	while ( grew ) {
		grew = false;
		for ( const [ key, value ] of Object.entries( candidates ) ) {
			if ( Object.hasOwn( out, key ) ) {
				continue;
			}
			if (
				Object.keys( out ).some( ( name ) =>
					value.includes( `var(--sup-${ name })` )
				)
			) {
				out[ key ] = value;
				grew = true;
			}
		}
	}
	return out;
}

function zeroed( tokens, prefix, zero ) {
	return Object.fromEntries(
		Object.keys( tokens )
			.filter( ( key ) => key.startsWith( prefix ) )
			.map( ( key ) => [ key, zero ] )
	);
}

function darkRules( scope, tokens ) {
	return [
		atRule(
			DARK_SYSTEM_MEDIA,
			rule(
				[ `${ scope }${ LIGHT_EXCLUDED }` ],
				tokens,
				[ [ 'color-scheme', 'dark' ] ],
				'\t'
			)
		),
		rule( [ `${ scope }${ DARK_EXPLICIT }` ], tokens, [
			[ 'color-scheme', 'dark' ],
		] ),
	];
}

function schemeRules( set ) {
	if ( set.brandAccent ) {
		return [];
	}
	return SCHEME_NAMES.filter( ( name ) => name !== DEFAULT_SCHEME ).flatMap(
		( name ) => {
			const scope = `body.admin-color-${ name } ${ SCOPE }`;
			const { light, dark } = set.schemes[ name ];
			return [
				rule( [ scope ], light ),
				atRule(
					DARK_SYSTEM_MEDIA,
					rule( [ `${ scope }${ LIGHT_EXCLUDED }` ], dark, [], '\t' )
				),
				rule( [ `${ scope }${ DARK_EXPLICIT }` ], dark ),
			];
		}
	);
}

/**
 * Renders the token set as the scoped `--sup-*` stylesheet.
 *
 * Deterministic: declarations are sorted, lines end in LF and the file ends
 * with one newline. Selector order: root (light), system dark, explicit dark,
 * admin-scheme accents (omitted with a brand accent), Arabic, compact
 * density, reduced motion.
 *
 * @param {TokenSet} set Token set.
 * @return {string} CSS.
 */
export function renderCss( set ) {
	const defaults = set.schemes[ DEFAULT_SCHEME ];
	const { light, dark } = set.semantic;
	const blocks = [
		HEADER,
		...( set.brandAccent ? [] : [ SCHEME_LINT_NOTE ] ),
		rule(
			[ SCOPE ],
			{
				...set.primitives,
				...defaults.light,
				...light,
				...set.component,
			},
			[ [ 'color-scheme', 'light' ] ]
		),
		...darkRules( SCOPE, {
			...defaults.dark,
			...changedFrom( light, dark ),
		} ),
		...schemeRules( set ),
		rule(
			ARABIC_LANGS.map( ( lang ) => `${ SCOPE }:lang(${ lang })` ),
			{
				...set.modifiers.arabic,
				...zeroed( light, 'letter-spacing-', '0' ),
			}
		),
		rule(
			[
				`${ SCOPE }[data-sup-density="compact"]`,
				`${ SCOPE } [data-sup-density="compact"]`,
			],
			withDependants( set.modifiers.compact, {
				...light,
				...set.component,
			} )
		),
		atRule(
			REDUCED_MOTION_MEDIA,
			rule(
				[ SCOPE ],
				{
					...zeroed( light, 'motion-duration-', '0ms' ),
					...zeroed( light, 'motion-distance-', '0' ),
				},
				[],
				'\t'
			)
		),
	];
	return `${ blocks.join( '\n\n' ) }\n`;
}
